#!/usr/bin/env bash
# Generates a dev engine configuration from the enabled inference services and
# prints it to stdout. `make run` calls this with NER/OCR/STT set to "1" for each
# service it started, so the engine config always matches the running stack and
# its resolved host ports. Nothing is emitted for a service that is off, so the
# server runs only what is up (and the built-in pattern recognizers always run).
set -euo pipefail

ner_port="${ELIDE_NER_PORT:-3200}"
ocr_port="${ELIDE_OCR_PORT:-3201}"
stt_port="${ELIDE_STT_PORT:-3202}"
ner_model="${ELIDE_NER_MODEL:-fastino/gliner2-privacy-filter-PII-multi}"
ocr_model="${ELIDE_OCR_MODEL:-db_resnet50+crnn_vgg16_bn}"
stt_model="${ELIDE_STT_MODEL:-large-v3-turbo}"

echo "# Generated by docker/gen-engine-config.sh for the running dev stack."
echo "# Regenerated on every \`make run\`; edits here are overwritten."

if [ "${NER:-}" = "1" ]; then
  cat <<EOF

[[recognizers.ner]]
name = "gliner2-ner"
kind = "bento"
base_url = "http://localhost:${ner_port}"
model = "${ner_model}"
EOF
fi

if [ "${OCR:-}" = "1" ]; then
  cat <<EOF

[[enrichers.ocr]]
name = "doctr-ocr"
kind = "bento"
base_url = "http://localhost:${ocr_port}"
model = "${ocr_model}"
EOF
fi

if [ "${STT:-}" = "1" ]; then
  cat <<EOF

[[enrichers.stt]]
name = "whisper-stt"
kind = "bento"
base_url = "http://localhost:${stt_port}"
model = "${stt_model}"
EOF
fi
